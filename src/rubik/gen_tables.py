from array import array
from itertools import permutations, product
from pathlib import Path

ROOT = Path(__file__).resolve().parent

# The R, B and D rows show where each corner comes from and how its twist changes.
SOURCE = (
    (1, 4, 2, 0, 3, 5, 6),
    (0, 1, 2, 4, 5, 6, 3),
    (0, 2, 5, 3, 1, 4, 6),
)
TWIST = (
    (1, 2, 0, 2, 1, 0, 0),
    (0, 0, 0, 1, 2, 1, 2),
    (0, 0, 0, 0, 0, 0, 0),
)


def quarter_tables():
    # Turn each face once and save the new permutation number.
    perms = list(permutations(range(7)))
    perm_rank = {p: i for i, p in enumerate(perms)}
    pm = []
    for p in perms:
        row = []
        for face in SOURCE:
            turned = tuple(p[i] for i in face)
            row.append(perm_rank[turned])
        pm.append(row)

    # The seven twists add up to a multiple of three, so the first six determine the last.
    om = []
    for six in product(range(3), repeat=6):
        orientation = six + ((-sum(six)) % 3,)
        row = []
        for face, twist in zip(SOURCE, TWIST):
            rank = 0
            for i in range(6):
                rank = 3 * rank + (orientation[face[i]] + twist[i]) % 3
            row.append(rank)
        om.append(row)

    return pm, om


def make_dictionary(pm, om):
    # Store the permutation in the high bits and the orientation in the low ten bits.
    seen = bytearray(5040 << 10)
    seen[0] = 1
    layer = array("I", [0])
    buckets = [[] for _ in pm]
    buckets[0].append(9)  # 9 marks the solved state.

    # Search outward from solved. Keep states up to five moves away and those exactly eleven moves away.
    for distance in range(1, 12):
        following = array("I")
        retain = distance <= 5 or distance == 11

        for key in layer:
            p = key >> 10
            o = key & 1023
            for face in range(3):
                np = p
                no = o
                for turn in range(3):
                    np = pm[np][face]
                    no = om[no][face]
                    child = (np << 10) | no
                    if seen[child]:
                        continue

                    seen[child] = 1
                    following.append(child)
                    if retain:
                        inverse = 3 * face + 2 - turn
                        tag = inverse + (16 if distance == 11 else 0)
                        buckets[np].append((no << 5) | tag)

        layer = following

    assert seen.count(1) == 3674160
    assert len(layer) == 2644

    # Each permutation row takes eight bytes. Its fourth entry points into the dictionary.
    entries = []
    p_rows = []
    for row, bucket in zip(pm, buckets):
        p_rows.extend(8 * q for q in row)
        p_rows.append(len(entries))
        entries.extend(sorted(bucket))
    p_rows.extend([0, 0, 0, len(entries)])

    o_rows = []
    for row in om:
        o_rows.extend(8 * q for q in row)
        o_rows.append(0)

    return p_rows, o_rows, entries


def emit(tables):
    note = "Generated by gen_tables.py. Move table offsets are in bytes."
    c = [f"/* {note} */", "/* clang-format off */"]
    asm = [f"# {note}", "    .section .rodata", "    .balign 2"]

    for name, values in zip(("perm_rows", "orient_rows", "dictionary"), tables):
        c.append("")
        asm.append("")
        c.append(f"static const uint16_t {name}[] = {{")
        asm.append(f".L{name}:")

        for start in range(0, len(values), 12):
            row = ", ".join(map(str, values[start:start + 12]))
            c.append(f"    {row},")
            asm.append(f"    .half {row}")
        c.append("};")

    c.append("/* clang-format on */")
    for name, lines in (("cube_tables.h", c), ("cube_tables.inc", asm)):
        content = "\n".join(lines) + "\n"
        (ROOT / name).write_bytes(content.encode("utf-8"))


if __name__ == "__main__":
    emit(make_dictionary(*quarter_tables()))
